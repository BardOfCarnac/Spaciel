import assert from 'node:assert/strict';
import {test} from 'node:test';
import {loadOneLineDescriptions,applyOneLineDescriptions} from '../src/locations/one-line-descriptions.js';

const register={count:3,records:[
  {id:'shop-1',name:'Example Shop',description:'Independent grocer selling supplies near the canal.',description_status:'existing_vendr'},
  {id:'bar-2',name:'Example Bar',description:'Former service garage now operating as a neighbourhood bar.',description_status:'draft_sourcebook_checked'},
  {id:'site-3',name:'Unknown Site',description:'',description_status:'missing'},
]};
test('applies existing copy and sourcebook drafts without altering type, tags or positions',()=>{
 const places=[
  {id:'shop-1',name:'Example Shop',role:'shopping:general',tags:[],x:123,z:45},
  {id:'bar-2',name:'Example Bar',role:'food:bars',affiliations:['Example faction'],x:67,z:89},
  {id:'site-3',name:'Unknown Site',role:'civic:public',x:2,z:3}
 ];
 const original=structuredClone(places);
 const result=applyOneLineDescriptions(places,loadOneLineDescriptions(register),{requireComplete:true});
 assert.deepEqual(result,{matched:3,described:2,missing:1,unmatched:0});
 assert.equal(places[2].short_description,''); // no autogenerated category fallback
 for(let i=0;i<places.length;i++)
   for(const key of ['id','name','role','tags','affiliations','x','z'])
     assert.deepEqual(places[i][key],original[i][key]);
});
test('rejects corrupt duplicate IDs and false ready flags',()=>{
 const duplicate={count:2,records:[register.records[0],register.records[0]]};
 assert.throws(()=>loadOneLineDescriptions(duplicate),/Duplicate/);
 const noCopy={count:1,records:[{...register.records[0],description:''}]};
 assert.throws(()=>loadOneLineDescriptions(noCopy),/empty description/);
});
test('rejects wrong IDs and mismatched names instead of guessing by name',()=>{
 const lookup=loadOneLineDescriptions(register);
 assert.throws(()=>applyOneLineDescriptions([{id:'shop-1',name:'Different Name'}],lookup),/ID\/name mismatch/);
 assert.throws(()=>applyOneLineDescriptions([{id:'unknown',name:'Example Shop'}],lookup,{requireComplete:true}),/Missing description/);
});
